using System;
using System.Collections.Generic;

namespace LastCallBBS.ModAPI;

/// <summary>Implemented by the loader. Mods use <see cref="ModSounds"/> instead.</summary>
public interface ISoundHost
{
    /// <summary>Plays a sound under Content\sounds\fx. Throws if it can't.</summary>
    void Play(string name, float volume);

    /// <summary>Starts mixing a source into the game's audio. Throws if it can't.</summary>
    IStreamControl Stream(IAudioSource source, float volume, IModLog log);
}

/// <summary>Implemented by the loader: one playing stream. Mods use <see cref="AudioStream"/> instead.</summary>
public interface IStreamControl
{
    float Volume { get; set; }
    bool IsPlaying { get; }
    long FramesPlayed { get; }
    void Stop();
}

/// <summary>
/// Audio generated by a mod, played by <see cref="ModSounds.Play(IAudioSource, float)"/>.
/// <see cref="Read"/> runs on the game's audio thread, not the main thread, about every 40 ms.
/// It must return quickly and must not touch the game.
/// </summary>
public interface IAudioSource
{
    /// <summary>
    /// Fills <paramref name="buffer"/> with up to <paramref name="frames"/> frames of interleaved
    /// stereo samples (left, right) at <see cref="ModSounds.SampleRate"/>, from -1 to 1. Returns the
    /// frames written; fewer than asked ends the stream. An exception ends the stream and is logged.
    /// </summary>
    int Read(float[] buffer, int frames);
}

/// <summary>A stream started by <see cref="ModSounds.Play(IAudioSource, float)"/>. Usable from any thread.</summary>
public sealed class AudioStream
{
    private readonly IStreamControl _control;

    public AudioStream(IStreamControl control) => _control = control;

    /// <summary>0 to 1, on top of the game's music volume. Takes effect at the next read.</summary>
    public float Volume
    {
        get => _control.Volume;
        set => _control.Volume = Math.Max(0f, Math.Min(1f, value));
    }

    /// <summary>False once the stream has ended, been stopped or failed.</summary>
    public bool IsPlaying => _control.IsPlaying;

    /// <summary>Frames read from the source so far. The audio heard lags behind by about <see cref="ModSounds.BufferFrames"/>.</summary>
    public long FramesPlayed => _control.FramesPlayed;

    /// <summary>Stops the stream. The source isn't read again.</summary>
    public void Stop() => _control.Stop();
}

/// <summary>
/// Plays the game's sound effects and audio generated by mods. Call it on the game's main thread
/// (program callbacks and hooks) once the game is running, not in OnLoad.
/// </summary>
public sealed class ModSounds
{
    /// <summary>The game's mixing rate, in frames per second.</summary>
    public const int SampleRate = 48000;

    /// <summary>The game's buffer, in frames: how far the audio heard lags behind <see cref="AudioStream.FramesPlayed"/>.</summary>
    public const int BufferFrames = 2048;

    private readonly ISoundHost _host;
    private readonly IModLog _log;
    private readonly HashSet<string> _failed = new(StringComparer.OrdinalIgnoreCase);

    public ModSounds(ISoundHost host, IModLog log)
    {
        _host = host;
        _log = log;
    }

    /// <summary>
    /// Plays one of the game's sounds, named by its path under Content\sounds\fx without the
    /// extension, such as "desktop/win_open". A name with a folder of variants, such as
    /// "desktop/load_m" (Content\sounds\fx\desktop\load_m.array), plays one of them at random.
    /// <paramref name="volume"/> is 0 to 1. Returns false if the sound couldn't play; the first
    /// failure for each name is logged.
    /// </summary>
    public bool PlayGameSound(string name, float volume = 1f)
    {
        if (string.IsNullOrWhiteSpace(name) || name.Contains(".."))
            throw new ArgumentException("a sound is named by its path under Content\\sounds\\fx, such as desktop/win_open", nameof(name));
        string clean = name.Replace('\\', '/').Trim('/');
        try
        {
            _host.Play(clean, Math.Max(0f, Math.Min(1f, volume)));
            return true;
        }
        catch (Exception e)
        {
            if (_failed.Add(clean))
                _log.Warn($"Sound {clean} couldn't play: {e.Message}");
            return false;
        }
    }

    /// <summary>
    /// Plays audio from <paramref name="source"/>, mixed with the game's sounds at the music volume.
    /// <paramref name="volume"/> is 0 to 1. Returns null if streams don't work on this build; the
    /// first failure is logged.
    /// </summary>
    public AudioStream Play(IAudioSource source, float volume = 1f)
    {
        if (source == null)
            throw new ArgumentNullException(nameof(source));
        try
        {
            return new AudioStream(_host.Stream(source, Math.Max(0f, Math.Min(1f, volume)), _log));
        }
        catch (Exception e)
        {
            if (_failed.Add("stream:"))
                _log.Warn($"Audio stream couldn't play: {e.Message}");
            return null;
        }
    }
}
