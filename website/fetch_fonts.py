"""Downloads the site's fonts and their licenses into theme/fonts/ and writes theme/fonts.css.

Run again after changing FONTS. Only the latin and latin-ext subsets are kept.
"""
import re
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "theme" / "fonts"
CSS = HERE / "theme" / "fonts.css"

# Google Fonts css2 family spec, and the family's folder in github.com/google/fonts.
FONTS = [
    ("Barlow:ital,wght@0,400;0,600;0,700;1,400;1,700", "barlow"),
    ("Electrolize", "electrolize"),
    ("Orbitron:wght@500..700", "orbitron"),
    ("JetBrains+Mono:ital,wght@0,100..800;1,100..800", "jetbrainsmono"),
]
SUBSETS = {"latin", "latin-ext"}
LICENSES = "https://raw.githubusercontent.com/google/fonts/main/ofl/{}/OFL.txt"
# A browser user agent, so the API serves woff2.
AGENT = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36"


def get(url):
    request = urllib.request.Request(url, headers={"User-Agent": AGENT})
    with urllib.request.urlopen(request, timeout=30) as response:
        return response.read()


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    query = "&".join("family=" + spec for spec, _ in FONTS)
    css = get(f"https://fonts.googleapis.com/css2?{query}&display=block").decode("utf-8")
    blocks = re.findall(r"/\* ([\w-]+) \*/\s*(@font-face \{.*?\})", css, re.S)
    if not blocks:
        raise SystemExit("unexpected response from Google Fonts")
    rules = []
    for subset, block in blocks:
        if subset not in SUBSETS:
            continue
        family = re.search(r"font-family: '([^']+)'", block).group(1)
        style = re.search(r"font-style: (\w+)", block).group(1)
        weight = re.search(r"font-weight: ([\d ]+);", block).group(1).replace(" ", "-")
        url = re.search(r"src: url\((\S+?)\)", block).group(1)
        name = f"{family.replace(' ', '')}-{style}-{weight}-{subset}.woff2"
        (OUT / name).write_bytes(get(url))
        rules.append(block.replace(url, f"fonts/{name}"))
        print(name)
    for _, folder in FONTS:
        (OUT / f"{folder}-OFL.txt").write_bytes(get(LICENSES.format(folder)).replace(b"\r\n", b"\n"))
        print(f"{folder}-OFL.txt")
    header = "/* Generated by fetch_fonts.py. Fonts are under the SIL Open Font License 1.1 (fonts/*-OFL.txt). */\n"
    CSS.write_bytes((header + "\n".join(rules) + "\n").encode("utf-8"))


if __name__ == "__main__":
    main()
