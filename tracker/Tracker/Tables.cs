    /// <summary>
    /// The note the replayer plays for a pattern period, "C-1" to "B-3": the first in the table at
    /// or below it. "---" for no note, "???" for periods below B-3.
    /// </summary>
    public static string NoteName(int period)
    {
        if (period == 0)
            return "---";
        int note = NoteIndex(period);
        return note < 36 ? NoteNames[note % 12] + (char)('1' + note / 12) : "???";
    }

    /// <summary>The replayer's note lookup: the first finetune-0 entry at or below the period, 0 to 36.</summary>
    public static int NoteIndex(int period)
    {
        int i = 0;
        while (i < 36 && period < Periods[i])
            i++;
        return i;
    }
